CREATE TABLE ARTICULO (
    id_articulo NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    nombre VARCHAR2(120) NOT NULL,
    estado VARCHAR2(20) DEFAULT 'DISPONIBLE' NOT NULL,
    codigo VARCHAR2(50) NOT NULL,
    id_categoria NUMBER NOT NULL,
    id_ubicacion NUMBER NOT NULL,
    id_responsable NUMBER NULL,
    valor_estimado NUMBER(10,2) DEFAULT 0 NOT NULL,
    descripcion VARCHAR2(500),
    fecha_creacion DATE DEFAULT SYSDATE NOT NULL,
    fecha_actualizacion DATE,
    CONSTRAINT ck_articulo_estado CHECK (estado IN ('DISPONIBLE','PRESTADO','MANTENIMIENTO','BAJA')),
    CONSTRAINT fk_articulo_categoria FOREIGN KEY (id_categoria) REFERENCES CATEGORIA(id_categoria),
    CONSTRAINT fk_articulo_ubicacion FOREIGN KEY (id_ubicacion) REFERENCES UBICACION(id_ubicacion),
    CONSTRAINT fk_articulo_responsable FOREIGN KEY (id_responsable) REFERENCES USUARIO(id_usuario) ON DELETE SET NULL
);

CREATE TABLE IMAGEN_ARTICULO (
