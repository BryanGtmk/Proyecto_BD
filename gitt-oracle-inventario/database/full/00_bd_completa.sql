CREATE TABLE ROL (
    id_rol NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    nombre_rol VARCHAR2(50) NOT NULL,
    CONSTRAINT uk_rol_nombre UNIQUE (nombre_rol)
);

CREATE TABLE USUARIO (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    nombre VARCHAR2(120) NOT NULL,
    correo VARCHAR2(150) NOT NULL,
    contrasena VARCHAR2(255) NOT NULL,
    id_rol NUMBER NOT NULL,
    fecha_creacion DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES ROL(id_rol)
);

CREATE TABLE DEPARTAMENTO (
    id_departamento NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    CONSTRAINT uk_departamento_nombre UNIQUE (nombre)
