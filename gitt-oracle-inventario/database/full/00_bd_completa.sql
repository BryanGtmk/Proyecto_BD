CREATE TABLE UBICACION (
    id_ubicacion NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    nombre VARCHAR2(120) NOT NULL,
    id_departamento NUMBER NOT NULL,
    CONSTRAINT fk_ubicacion_departamento FOREIGN KEY (id_departamento) REFERENCES DEPARTAMENTO(id_departamento)
