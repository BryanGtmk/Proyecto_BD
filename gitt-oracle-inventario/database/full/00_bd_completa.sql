CREATE OR REPLACE TRIGGER trg_articulo_auditoria
AFTER INSERT OR UPDATE OR DELETE ON ARTICULO
FOR EACH ROW
DECLARE
    v_usuario NUMBER;
    v_accion VARCHAR2(20);
    v_codigo VARCHAR2(50);
BEGIN
    IF INSERTING THEN
        v_accion := 'INSERT';
        v_usuario := NVL(:NEW.id_responsable, 1);
        v_codigo := :NEW.codigo;
    ELSIF UPDATING THEN
        v_accion := 'UPDATE';
        v_usuario := NVL(:NEW.id_responsable, NVL(:OLD.id_responsable, 1));
        v_codigo := :NEW.codigo;
    ELSE
        v_accion := 'DELETE';
        v_usuario := NVL(:OLD.id_responsable, 1);
        v_codigo := :OLD.codigo;
    END IF;

    INSERT INTO AUDITORIA (accion, fecha, id_usuario, tabla, descripcion)
    VALUES (
        v_accion,
        SYSDATE,
        v_usuario,
        'ARTICULO',
        'Auditoria automatica del articulo ' || v_codigo
    );
END;
/

CREATE OR REPLACE TRIGGER trg_detalle_prestamo_estado
AFTER INSERT OR UPDATE OF id_articulo ON DETALLE_PRESTAMO
FOR EACH ROW
DECLARE
    v_estado_prestamo PRESTAMO.estado%TYPE;
BEGIN
    SELECT estado INTO v_estado_prestamo FROM PRESTAMO WHERE id_prestamo = :NEW.id_prestamo;
    IF v_estado_prestamo = 'ACTIVO' THEN
        UPDATE ARTICULO SET estado = 'PRESTADO', fecha_actualizacion = SYSDATE WHERE id_articulo = :NEW.id_articulo;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_detalle_prestamo_validar
FOR INSERT OR UPDATE OF id_articulo, id_prestamo ON DETALLE_PRESTAMO
COMPOUND TRIGGER
    TYPE t_articulos IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    g_articulos t_articulos;
    g_count PLS_INTEGER := 0;
AFTER EACH ROW IS
BEGIN
    g_count := g_count + 1;
    g_articulos(g_count) := :NEW.id_articulo;
END AFTER EACH ROW;
AFTER STATEMENT IS
    v_total NUMBER;
BEGIN
    FOR i IN 1 .. g_count LOOP
        SELECT COUNT(*)
        INTO v_total
        FROM DETALLE_PRESTAMO dp
        JOIN PRESTAMO p ON p.id_prestamo = dp.id_prestamo
        WHERE dp.id_articulo = g_articulos(i)
          AND p.estado = 'ACTIVO';

        IF v_total > 1 THEN
            RAISE_APPLICATION_ERROR(-20001, 'El articulo ya se encuentra en un prestamo activo.');
        END IF;
    END LOOP;
END AFTER STATEMENT;
END;
/

CREATE OR REPLACE TRIGGER trg_prestamo_devolucion
AFTER UPDATE OF estado ON PRESTAMO
FOR EACH ROW
WHEN (NEW.estado = 'DEVUELTO' AND OLD.estado <> 'DEVUELTO')
BEGIN
    FOR r IN (SELECT id_articulo FROM DETALLE_PRESTAMO WHERE id_prestamo = :NEW.id_prestamo) LOOP
        UPDATE ARTICULO SET estado = 'DISPONIBLE', fecha_actualizacion = SYSDATE WHERE id_articulo = r.id_articulo;
        INSERT INTO MOVIMIENTO (fecha, tipo, id_articulo, observacion)
        VALUES (SYSDATE, 'DEVOLUCION', r.id_articulo, 'Devolucion registrada por trigger');
    END LOOP;

    INSERT INTO AUDITORIA (accion, fecha, id_usuario, tabla, descripcion)
    VALUES ('DEVOLUCION', SYSDATE, :NEW.id_usuario, 'PRESTAMO', 'Devolucion del prestamo ' || :NEW.id_prestamo);
END;
